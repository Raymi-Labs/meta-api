func DoWssRequest(a Adaptor, c *gin.Context, info *common.RelayInfo, requestBody io.Reader) (*websocket.Conn, error) {
	fullRequestURL, err := a.GetRequestURL(info)
	if err != nil {
		return nil, fmt.Errorf("get request url failed: %w", err)
	}
	targetHeader := http.Header{}
	err = a.SetupRequestHeader(c, &targetHeader, info)
	if err != nil {
		return nil, fmt.Errorf("setup request header failed: %w", err)
	}
	attachNewAPIRequestIDHeader(targetHeader, info)
	// 在 SetupRequestHeader 之后应用 Header Override，确保用户设置优先级最高
	// 这样可以覆盖默认的 Authorization header 设置
	headerOverride, err := processHeaderOverride(info, c)
	if err != nil {
		return nil, err
	}
	for key, value := range headerOverride {
		targetHeader.Set(key, value)
	}
	targetHeader.Set("Content-Type", c.Request.Header.Get("Content-Type"))
	if err = applyCPAIdentity(targetHeader, info); err != nil {
		return nil, err
	}
	// Keep the existing OpenAI transport unchanged; Ali TTS uses the configured
	// channel proxy/TLS transport and request cancellation during the handshake.
	dialer := *websocket.DefaultDialer
	if info.RelayFormat == types.RelayFormatAliTTS || (info.ChannelType == appconstant.ChannelTypeAli && info.RelayMode == constant.RelayModeAudioSpeech) {
		client, clientErr := service.GetHttpClientWithProxy(info.ChannelSetting.Proxy)
		if clientErr != nil {
			return nil, clientErr
		}
		if transport, ok := client.Transport.(*http.Transport); ok {
			dialer.Proxy = transport.Proxy
			dialer.NetDialContext = transport.DialContext
			dialer.TLSClientConfig = transport.TLSClientConfig
		}
		dialer.HandshakeTimeout = 15 * time.Second
	}
	targetConn, handshake, err := dialer.DialContext(c.Request.Context(), fullRequestURL, targetHeader)
	if err != nil && handshake != nil && handshake.Body != nil {
		_ = handshake.Body.Close()
	}
	if err != nil {
		return nil, fmt.Errorf("dial failed to %s: %w", fullRequestURL, err)
	}
	// send request body
	//all, err := io.ReadAll(requestBody)
	//err = service.WssString(c, targetConn, string(all))
	return targetConn, nil
}

func DoRequest(c *gin.Context, req *http.Request, info *common.RelayInfo) (*http.Response, error) {
	return doRequest(c, req, info)
}

func newDoRequestError(c *gin.Context, err error) *types.NewAPIError {
	if c != nil && c.Request != nil {
		if ctxErr := c.Request.Context().Err(); ctxErr != nil {
			logger.LogInfo(c, "request canceled by client: "+ctxErr.Error())
			if errors.Is(ctxErr, context.Canceled) {
				return types.NewClientCanceledError(types.ErrOptionWithHideErrMsg("client request canceled"))
			}
			return types.NewError(ctxErr, types.ErrorCodeDoRequestFailed,
				types.ErrOptionWithSkipRetry(),
				types.ErrOptionWithHideErrMsg("client request canceled"))
		}
	}
	logger.LogError(c, "do request failed: "+err.Error())
	if strings.Contains(err.Error(), "timeout awaiting response headers") {
		return types.NewErrorWithStatusCode(
			err,
			types.ErrorCodeDoRequestFailed,
			http.StatusGatewayTimeout,
			types.ErrOptionWithSkipRetry(),
			types.ErrOptionWithHideErrMsg("upstream response header timeout"))
	}
	return types.NewError(err, types.ErrorCodeDoRequestFailed, types.ErrOptionWithHideErrMsg("upstream error: do request failed"))
}

func shouldUseImageHTTPClient(info *common.RelayInfo) bool {
	if info == nil {
		return false
	}
	switch info.RelayMode {
	case constant.RelayModeImagesGenerations, constant.RelayModeImagesEdits:
		return true
	case constant.RelayModeResponses, constant.RelayModeResponsesCompact:
		if request, ok := info.Request.(*dto.OpenAIResponsesRequest); ok && request.HasImageGenerationTool() {
			return true
		}
		if info.ResponsesUsageInfo != nil {
			_, ok := info.ResponsesUsageInfo.BuiltInTools[dto.BuildInToolImageGeneration]
			return ok
		}
	}
	return false
}

func channelNonStreamHeaderTimeout(info *common.RelayInfo) time.Duration {
	if info == nil || info.ChannelMeta == nil || info.IsStream || shouldUseImageHTTPClient(info) {
		return 0
	}
	seconds := info.ChannelSetting.NonStreamResponseHeaderTimeoutSec
	if seconds <= 0 || seconds > 600 {
		return 0
	}
	switch info.RelayMode {
	case constant.RelayModeChatCompletions, constant.RelayModeCompletions, constant.RelayModeResponses, constant.RelayModeVideoSubmit:
		return time.Duration(seconds) * time.Second
	}
	return 0
}

func doRequest(c *gin.Context, req *http.Request, info *common.RelayInfo) (*http.Response, error) {
	if err := applyCPAIdentity(req.Header, info); err != nil {
		return nil, err
	}
	var client *http.Client
	var err error
	isImageRequest := shouldUseImageHTTPClient(info)
	if info.ChannelSetting.Proxy != "" {
		client, err = service.NewProxyHttpClient(info.ChannelSetting.Proxy, isImageRequest)
		if err != nil {
			return nil, fmt.Errorf("new proxy http client failed: %w", err)
		}
	} else if isImageRequest {
		client = service.GetImageHttpClient()
	} else {
		client = service.GetHttpClient()
	}
	wait := channelNonStreamHeaderTimeout(info)
	if wait > 0 {
		client, err = service.WithResponseHeaderTimeout(client, wait)
		if err != nil {
			return nil, fmt.Errorf("configure channel header timeout: %w", err)
		}
	}
	service.RecordRelayHTTPTimeout(c, client, wait > 0)

	if info.IsStream {
		helper.SetEventStreamHeaders(c)
		// 处理流式请求的 ping 保活
		if pingEnabled, pingInterval := helper.GetStreamPingConfig(info); pingEnabled {
			stopPinger := helper.StartStreamKeepAlive(c, pingInterval, info.RelayFormat)
			defer stopPinger()
		}
	}

	client = claudeClientContextHTTPClient(client, info)
	client = cpaIdentityHTTPClient(client, info)
	client = openCodeSessionHTTPClient(client, req)
	if info.TaskRelayInfo != nil {
		client = taskHeaderOverrideHTTPClient(client, info)
	}
	resp, err := client.Do(req)
	if err != nil {
		return nil, newDoRequestError(c, err)
	}
	if resp == nil {
		return nil, errors.New("resp is nil")
	}
	service.RecordUpstreamRequestID(c, resp.Header)

	_ = req.Body.Close()
	_ = c.Request.Body.Close()
	return resp, nil
}

func DoTaskApiRequest(a TaskAdaptor, c *gin.Context, info *common.RelayInfo, requestBody io.Reader) (*http.Response, error) {
	fullRequestURL, err := a.BuildRequestURL(info)
	if err != nil {
		return nil, err
	}
	req, err := http.NewRequest(c.Request.Method, fullRequestURL, requestBody)
	if err != nil {
		return nil, fmt.Errorf("new request failed: %w", err)
	}
	req.GetBody = func() (io.ReadCloser, error) {
		return io.NopCloser(requestBody), nil
	}

	err = a.BuildRequestHeader(c, req, info)
	if err != nil {
		return nil, fmt.Errorf("setup request header failed: %w", err)
	}
	if err := ApplyHeaderOverride(info, c, req); err != nil {
		return nil, err
	}
	resp, err := doRequest(c, req, info)
	if err != nil {
		return nil, fmt.Errorf("do request failed: %w", err)
	}
	return resp, nil
}

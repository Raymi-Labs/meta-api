import { readFileSync, writeFileSync } from 'node:fs';
import { format, resolveConfig } from 'prettier';

const names = ['guide', 'console', 'api', 'integrations'];
const root = new URL('../../docs/handbook/', import.meta.url);
const entries = names.flatMap((name) =>
  JSON.parse(readFileSync(new URL(`${name}-catalog.json`, root), 'utf8')),
);
const imports = entries.map(
  (entry, index) =>
    `import article${index} from '../../../../docs/handbook/${entry.file}?raw';`,
);
const source = `/*
Copyright (C) 2025 QuantumNous

This program is free software: you can redistribute it and/or modify
it under the terms of the GNU Affero General Public License as
published by the Free Software Foundation, either version 3 of the
License, or (at your option) any later version.

This program is distributed in the hope that it will be useful,
but WITHOUT ANY WARRANTY; without even the implied warranty of
MERCHANTABILITY or FITNESS FOR A PARTICULAR PURPOSE. See the
GNU Affero General Public License for more details.

You should have received a copy of the GNU Affero General Public License
along with this program. If not, see <https://www.gnu.org/licenses/>.

For commercial licensing, please contact support@quantumnous.com
*/

// Generated by bun run sync:handbook. Edit docs/handbook catalogs and Markdown.\n${imports.join('\n')}\n\nexport const HANDBOOK_DOCS = [\n${entries
  .map(
    ({ file, ...entry }, index) =>
      `  { ...${JSON.stringify(entry)}, content: article${index} },`,
  )
  .join('\n')}\n];\n`;
const destination = new URL(
  '../src/pages/Docs/handbook.generated.js',
  import.meta.url,
);
const output = await format(source, {
  ...(await resolveConfig(destination.pathname)),
  filepath: destination.pathname,
});
if (process.argv.includes('--check')) {
  if (readFileSync(destination, 'utf8') !== output) {
    throw new Error('Handbook index is stale. Run bun run sync:handbook.');
  }
} else {
  writeFileSync(destination, output);
}
